"""Flag ghost-like names and check the flag.

The rule: a name is ghost-like if it lacks at least 4 of 5 public-identity markers
(verified badge, bio, external link, gallery photo, Spotify "This Is" playlist). The rule uses
no production or listening data, so what flagged names have in common on those is a finding,
not an input.

Adds `ghost` to artist_features.parquet and writes:
  convergence_reference_sets.csv  share flagged in groups the rule never saw
  convergence_profile.csv         flagged vs not flagged on the same playlists, in raw units
  notes/convergence.md

    python -m src.features.convergence
"""
from __future__ import annotations

import pandas as pd

from src.load import PROCESSED, PROJECT

MIN_MISSING = 4  # of 5 identity markers

# External reference groups, matched on the artist's dominant credit Source.
KNOWN_SUPPLIERS = {"Firefly Entertainment": "Firefly", "Epidemic Sound": "Epidemic"}
CLASSICAL_MAJORS = ["Deutsche Grammophon", "Decca", "Sony Classical", "Warner Classics"]


def flag(df: pd.DataFrame) -> pd.Series:
    return (df.identity_score * 5).round() >= MIN_MISSING


def reference_rates(df: pd.DataFrame) -> pd.DataFrame:
    src = df.source_dom_raw.fillna("")
    groups = {name: src.str.contains(pat, case=False, regex=False) for name, pat in KNOWN_SUPPLIERS.items()}
    groups["Classical majors"] = src.str.contains("|".join(CLASSICAL_MAJORS), case=False)
    groups["Genre-playlist artists"] = df.group == "genre"
    return pd.DataFrame([{"name": k, "n_artists": int(m.sum()), "share_ghost": df.loc[m, "ghost"].mean()}
                         for k, m in groups.items()])


def profile(df: pd.DataFrame) -> pd.DataFrame:
    """Flagged vs not flagged among functional-playlist names, in plain units."""
    f = df[df.group == "functional"]
    rows = []
    for lab, d in [("flagged", f[f.ghost]), ("not flagged", f[~f.ghost])]:
        rows.append({
            "group": lab, "n": len(d),
            "house_size_median": d.registrant_house_size.median(),
            "followers_per_1000_listeners": 1000 * 10 ** d.log_fpl.median(),
            "alias_only_tracks": d.alias_only_share.mean(),
            "self_labelled": d.self_source_share.gt(0.5).mean(),
        })
    return pd.DataFrame(rows).set_index("group")


def sensitivity(df: pd.DataFrame) -> pd.DataFrame:
    """How much the headline depends on where the line is drawn. Alternative definitions:
    3, 4 (the rule) or 5 of 5 markers missing, and the rule corrected by followers per listener
    (flagged names with >= 25 followers per 1,000 listeners un-flagged; unflagged names with
    <= 1.4 flagged; the medians of real and flagged names in Table 1)."""
    from src.common import placement

    pa = placement()
    pa = pa[pa.is_primary & (pa.group == "functional")]
    src = df.source_dom_raw.fillna("")
    majors = src.str.contains("|".join(CLASSICAL_MAJORS), case=False)
    k = (df.identity_score * 5).round()
    fpl = 1000 * df.followers / df.monthly_listeners.where(df.monthly_listeners > 0)
    corrected = df.ghost.copy()
    corrected[df.ghost & (fpl >= 25)] = False
    corrected[~df.ghost & (fpl <= 1.4)] = True
    rules = {"at least 3 missing": k >= 3, "at least 4 missing (the rule)": k >= 4,
             "all 5 missing": k >= 5, "rule corrected by followers per listener": corrected}
    rows = []
    for name, lab in rules.items():
        lab = lab.astype(bool)
        rows.append({"rule": name, "n": int(lab.sum()),
                     "slot_share": float(pa.artist_id.map(lab).mean()),
                     "firefly": float(lab[src.str.contains("Firefly", regex=False)].mean()),
                     "majors": float(lab[majors].mean())})
    return pd.DataFrame(rows)


def main() -> None:
    path = PROCESSED / "artist_features.parquet"
    df = pd.read_parquet(path)
    df["ghost"] = flag(df)
    df.to_parquet(path)

    ref = reference_rates(df)
    ref.to_csv(PROCESSED / "convergence_reference_sets.csv", index=False)
    prof = profile(df)
    prof.to_csv(PROCESSED / "convergence_profile.csv")
    sens = sensitivity(df)
    sens.to_csv(PROCESSED / "convergence_sensitivity.csv", index=False)

    lines = [
        "# Ghost-like names",
        "",
        "Generated by `python -m src.features.convergence`.",
        "",
        f"A name is ghost-like if it lacks at least {MIN_MISSING} of 5 identity markers (verified, bio, "
        "external link, gallery photo, Spotify 'This Is' playlist). "
        f"{int(df.ghost.sum()):,} of {len(df):,} names are flagged.",
        "",
        "## Groups the rule never saw",
        "",
        ref.assign(share_ghost=ref.share_ghost.map("{:.0%}".format)).to_markdown(index=False),
        "",
        "## Flagged and not flagged names on the same (functional) playlists",
        "",
        prof.round(3).to_markdown(),
        "",
        "## How much the definition matters",
        "",
        sens.round(3).to_markdown(index=False),
    ]
    (PROJECT / "notes" / "convergence.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
